export const B = { ru, en };
export const strings = (l: L) => B[l];

export const ago = (ms: number, l: L) => {
  const s = Math.max(1, Math.round((Date.now() - ms) / 1000));
  const rtf = new Intl.RelativeTimeFormat(l === "ru" ? "ru" : "en", { numeric: "auto" });
  if (s < 60) return rtf.format(-s, "second");
  if (s < 3600) return rtf.format(-Math.round(s / 60), "minute");
  if (s < 86400) return rtf.format(-Math.round(s / 3600), "hour");
  if (s < 30 * 86400) return rtf.format(-Math.round(s / 86400), "day");
  return new Date(ms).toLocaleDateString(l === "ru" ? "ru-RU" : "en-US", {
    day: "numeric",
    month: "short",
    year: "numeric",
  });
};
export const dateOf = (ms: number, l: L) =>
  new Date(ms).toLocaleDateString(l === "ru" ? "ru-RU" : "en-US", {
    day: "numeric",
    month: "long",
    year: "numeric",
  });
